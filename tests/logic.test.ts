  assert.ok(s);
  assert.equal(s!.meals.length, 1);
  assert.equal(s!.readings.length, 1);
  assert.equal(s!.profile.meal_carb_target, 60);
  assert.equal(s!.profile.glucose_high, 180);
  assert.equal(s!.profile.diet, "veg");
