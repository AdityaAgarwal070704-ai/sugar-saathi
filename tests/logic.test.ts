import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { nutritionOf } from "../lib/carbs";
import { mealTips } from "../lib/insights";
import { pairMeals } from "../lib/pairing";
import { weekStats } from "../lib/stats";
import { parseGlucoseCsv } from "../lib/csv";
import { hasDosingAdvice } from "../lib/guardrails";
import type { Food, MealRow, ReadingRow } from "../lib/types";

const foods: Food[] = JSON.parse(readFileSync("data/foods.json", "utf8")).foods;
const profile = { meal_carb_target: 60, glucose_low: 70, glucose_high: 180 };

test("nutrition adds up from the table", () => {
  const n = nutritionOf([{ foodId: "roti", count: 2 }, { foodId: "dal", count: 1 }, { foodId: "aloo_sabzi", count: 1 }], foods);
  assert.equal(n.carbs, 63);
  assert.equal(n.protein, 17); // 6 + 8 + 3
  assert.equal(n.gl, Math.round((62 * 30) / 100 + (30 * 15) / 100 + (70 * 18) / 100));
});

test("tips: big rice meal is flagged and offers brown rice", () => {
  const t = mealTips([{ foodId: "white_rice", count: 2.5 }], foods, profile);
  assert.equal(t.rating, "higher");
  assert.ok(t.improve.some((x) => /above your 60 g/.test(x)));
  assert.ok(t.swaps.some((s) => /brown rice/i.test(s.to)));
});

test("tips: dal and sabzi meal gets praise", () => {
  const t = mealTips([{ foodId: "roti", count: 2 }, { foodId: "dal", count: 1 }, { foodId: "bhindi_sabzi", count: 1 }], foods, profile);
  assert.ok(t.good.some((x) => /Dal/.test(x)));
  assert.ok(t.good.some((x) => /vegetable/.test(x)));
});

test("tips never contain dosing language", () => {
  const all = foods.flatMap((f) => {
    const t = mealTips([{ foodId: f.id, count: 3 }], foods, profile);
    return [t.headline, ...t.good, ...t.improve, ...t.swaps.map((s) => s.note)];
  });
  assert.ok(all.every((s) => !hasDosingAdvice(s)), "a tip sounded like dosing advice");
});

const meal = (id: string, iso: string, items = [{ foodId: "roti", count: 2, typed: "roti" }]): MealRow => ({
  id, eaten_at: iso, meal_type: "lunch", text: "x", items, carbs: 30, fibre: 4, protein: 6, gl: 18,
});
const reading = (id: string, iso: string, value: number): ReadingRow => ({ id, measured_at: iso, value, source: "manual" });

test("pairing picks pre within 45 min before and post near 2 hours", () => {
  const m = meal("1", "2026-10-20T08:00:00Z");
  const r = [
    reading("a", "2026-10-20T07:30:00Z", 112),
    reading("b", "2026-10-20T07:00:00Z", 99), // too early
    reading("c", "2026-10-20T10:05:00Z", 168),
    reading("d", "2026-10-20T11:30:00Z", 140), // too late
  ];
  const [p] = pairMeals([m], r);
  assert.equal(p.pre?.value, 112);
  assert.equal(p.post?.value, 168);
  assert.equal(p.rise, 56);
});

test("pairing leaves rise empty when a reading is missing", () => {
  const [p] = pairMeals([meal("1", "2026-10-20T08:00:00Z")], [reading("a", "2026-10-20T07:50:00Z", 100)]);
  assert.equal(p.rise, null);
});

test("week stats: average rise and per-dish rise", () => {
  const ms = [meal("1", "2026-10-20T08:00:00Z"), meal("2", "2026-10-21T08:00:00Z")];
  const rs = [
    reading("a", "2026-10-20T07:50:00Z", 100), reading("b", "2026-10-20T10:00:00Z", 160),
    reading("c", "2026-10-21T07:50:00Z", 110), reading("d", "2026-10-21T10:00:00Z", 190),
  ];
  const paired = pairMeals(ms, rs);
  const s = weekStats(paired, rs, profile, foods);
  assert.equal(s.avgRise, 70);
  assert.equal(s.dishRises[0].foodId, "roti");
  assert.equal(s.inRangePct, 75);
});

test("csv: LibreView style, day-first dates", () => {
  const csv = [
    "Glucose Data,Generated on,22-10-2026 09:00,Generated by,Aditya",
    "Device,Serial Number,Device Timestamp,Record Type,Historic Glucose mg/dL,Scan Glucose mg/dL",
    "FreeStyle,ABC,20-10-2026 07:50,0,112,",
    "FreeStyle,ABC,20-10-2026 10:00,0,168,",
    "FreeStyle,ABC,20-10-2026 10:05,1,,171",
    "FreeStyle,ABC,not a date,0,100,",
  ].join("\n");
  const r = parseGlucoseCsv(csv);
  assert.equal(r.readings.length, 3);
  assert.equal(r.skipped, 1);
  assert.equal(r.readings[2].value, 171);
  assert.equal(new Date(r.readings[0].measured_at).getDate(), 20);
});

test("csv: mmol/L is converted", () => {
  const r = parseGlucoseCsv("Time,Glucose mmol/L\n2026-10-20 08:00,6.1\n2026-10-20 10:00,9.4");
  assert.equal(r.unit, "mmol/L");
  assert.deepEqual(r.readings.map((x) => x.value), [110, 169]);
});

test("csv: not a glucose file", () => {
  assert.ok(parseGlucoseCsv("a,b\n1,2").error);
});

test("guardrail blocks dosing and medication talk, allows food advice", () => {
  for (const bad of ["Take 4 units of insulin before this", "increase your metformin", "Your insulin dose should change", "Consider tirzepatide"]) {
    assert.ok(hasDosingAdvice(bad), bad);
  }
  for (const ok of ["Try a smaller portion of rice and add dal.", "Discuss these patterns with your educator."]) {
    assert.ok(!hasDosingAdvice(ok), ok);
  }
});

import { fromPersisted, mergeReadings, toPersisted, EMPTY_STATE } from "../lib/store-core";

test("store: round trip keeps meals, readings and goals", () => {
  const m = meal("m1", "2026-10-20T08:00:00Z");
  const merged = mergeReadings([], [{ measured_at: "2026-10-20T07:50:00Z", value: 112, source: "manual" }]);
  const state = { meals: [m], readings: merged.readings, profile: { ...EMPTY_STATE.profile, meal_carb_target: 50 } };
  const back = fromPersisted(JSON.parse(JSON.stringify(toPersisted(state))));
  assert.ok(back);
  assert.equal(back!.meals.length, 1);
  assert.equal(back!.readings[0].value, 112);
  assert.equal(back!.profile.meal_carb_target, 50);
});

test("store: duplicates are ignored and bad values rejected", () => {
  const a = mergeReadings([], [{ measured_at: "2026-10-20T07:50:00Z", value: 112, source: "csv" }]);
  const b = mergeReadings(a.readings, [
    { measured_at: "2026-10-20T07:50:00Z", value: 112, source: "csv" },
    { measured_at: "2026-10-20T08:50:00Z", value: 20, source: "manual" },
    { measured_at: "not a date", value: 100, source: "manual" },
  ]);
  assert.equal(b.added, 0);
  assert.equal(b.readings.length, 1);
});

test("store: malformed or hostile backup data is dropped, not trusted", () => {
  assert.equal(fromPersisted(null), null);
  assert.equal(fromPersisted({ v: 2 }), null);
  const s = fromPersisted({
    v: 1,
    meals: [{ id: 1 }, meal("ok", "2026-10-20T08:00:00Z"), { ...meal("bad", "nope") }],
    readings: [[1, 2, 0], "x", [1_760_000_000_000, 130, 1]],
    profile: { meal_carb_target: 9999, glucose_low: 90, glucose_high: 50, diet: "<script>" },
  });
  assert.ok(s);
  assert.equal(s!.meals.length, 1);
  assert.equal(s!.readings.length, 1);
  assert.equal(s!.profile.meal_carb_target, 60);
  assert.equal(s!.profile.glucose_high, 180);
  assert.equal(s!.profile.diet, "veg");
});
